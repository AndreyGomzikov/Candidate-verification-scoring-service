"""Real PostgreSQL regression checks for additive migrations and cooldown ledger.

This test deliberately drops columns to simulate a legacy deployment. It only
runs against a specifically authorized disposable gatekeeper_ci database and
performs destructive operations INSIDE a fresh, test-owned PostgreSQL schema.
The schema is dropped even if an assertion or migration fails. Never point this
at production.
"""
from __future__ import annotations

import asyncio
import os
from datetime import datetime, timedelta, timezone
from uuid import uuid4

import pytest
from sqlalchemy import select, text
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine

from app.db import Database
from app.models import CooldownDeclinedJoinRequest as Attempt


class _IsolatedSchemaDatabase(Database):
    """Run the actual Database methods with every connection in one test schema.

    asyncpg's server_settings sets search_path at connection establishment,
    including when SQLAlchemy opens another connection from the pool. No
    production code needs a test-specific configuration option.
    """

    def __init__(self, url: str, schema: str) -> None:
        self.engine = create_async_engine(
            url,
            future=True,
            hide_parameters=True,
            connect_args={"server_settings": {"search_path": schema}},
        )
        self.sessions = async_sessionmaker(
            self.engine, class_=AsyncSession, expire_on_commit=False
        )


def test_postgres_legacy_request_date_migration_and_cooldown_ledger():
    url = os.getenv("GATEKEEPER_TEST_POSTGRES_URL")
    if not url:
        pytest.skip("GATEKEEPER_TEST_POSTGRES_URL is not set")
    if not url.startswith("postgresql+asyncpg://"):
        pytest.fail("Integration checks require postgresql+asyncpg://")
    # This test drops columns. Only a disposable CI database with explicit
    # permission may be used, even though the test owns its isolated schema.
    if make_url(url).database != "gatekeeper_ci" or os.getenv(
        "GATEKEEPER_ALLOW_DESTRUCTIVE_SCHEMA_TEST"
    ) != "yes":
        pytest.skip("Migration simulation requires disposable gatekeeper_ci and explicit opt-in")
    pytest.importorskip("asyncpg")

    async def scenario() -> None:
        # A new schema every time makes the test rerunnable in the SAME database
        # and keeps unrelated test data and existing candidate timestamps intact.
        schema = f"gatekeeper_migration_test_{uuid4().hex}"
        admin_db = Database(url)
        db = None
        other = None
        created_schema = False
        try:
            async with admin_db.engine.begin() as conn:
                # The schema name is generated by uuid4, never user input.
                await conn.execute(text(f'CREATE SCHEMA "{schema}"'))
            created_schema = True

            db = _IsolatedSchemaDatabase(url, schema)
            other = _IsolatedSchemaDatabase(url, schema)
            async with db.engine.connect() as conn:
                assert await conn.scalar(text("SELECT current_schema()")) == schema
            async with other.engine.connect() as conn:
                assert await conn.scalar(text("SELECT current_schema()")) == schema

            await db.init()
            when = datetime(2026, 11, 6, 10, tzinfo=timezone.utc)
            user, chat = 710000123, -100710000123
            candidate = await db.create_candidate(
                user_id=user, user_chat_id=user, target_chat_id=chat,
                username="test", first_name="Migration", request_date=when,
            )
            await db.record_cooldown_declined_request(user, chat, when)
            await db.record_cooldown_declined_request(user, chat, when)
            new_attempt = when + timedelta(minutes=1)
            assert await db.begin_cooldown_decline(user, chat, new_attempt)
            assert not await other.begin_cooldown_decline(user, chat, new_attempt)
            assert await other.complete_cooldown_decline(
                user, chat, new_attempt, confirmed=False,
            )
            assert len(await db.list_unalerted_cooldown_intents()) == 1

            # The latest attempt includes pending and uncertain rows. The old
            # assertion incorrectly expected 'when' instead of 'new_attempt'.
            assert await other.last_cooldown_declined_request_date(user, chat) == new_attempt
            assert await other.last_cooldown_declined_request_date(user, chat - 1) is None
            assert await other.last_cooldown_declined_request_date(user + 1, chat) is None
            later_attempt = when + timedelta(minutes=2)
            await other.record_cooldown_declined_request(user, chat, later_attempt)
            assert await db.last_cooldown_declined_request_date(user, chat) == later_attempt

            # Simulate legacy tables that lack these columns. Other tables in
            # the main database are never affected: search_path is test-only.
            async with db.engine.begin() as conn:
                await conn.execute(text("ALTER TABLE candidates DROP COLUMN request_date"))
                await conn.execute(text(
                    "ALTER TABLE cooldown_declined_join_requests DROP COLUMN status"
                ))
                await conn.execute(text(
                    "ALTER TABLE cooldown_declined_join_requests DROP COLUMN confirmed_at"
                ))
                await conn.execute(text(
                    "ALTER TABLE cooldown_declined_join_requests DROP COLUMN alerted_at"
                ))

            await db.init()
            await db.init()  # Repeated migrations must be idempotent.
            preserved = await db.get_candidate(candidate.id)
            assert preserved is not None
            assert preserved.user_id == user
            assert preserved.request_date is None  # Unknown for legacy rows
            async with db.sessions() as session:
                records = (await session.scalars(select(Attempt))).all()
                assert len(records) == 3  # Identical dates were deduplicated.
                assert all(record.status == "declined" for record in records)
            assert await other.last_cooldown_declined_request_date(user, chat) == later_attempt
        finally:
            # Close all schema-scoped connections before dropping the schema.
            # DROP CASCADE cleans up every test row even on assertion failures.
            try:
                if other is not None:
                    await other.close()
                if db is not None:
                    await db.close()
                if created_schema:
                    async with admin_db.engine.begin() as conn:
                        await conn.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
            finally:
                await admin_db.close()

    asyncio.run(scenario())
